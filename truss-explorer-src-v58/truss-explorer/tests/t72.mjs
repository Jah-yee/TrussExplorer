import { chromium } from 'playwright';
import http from 'http'; import fs from 'fs';
const D = '/tmp/claude-0/-home-claude/41c905c5-17de-5fda-854e-d445bf24c0d9/scratchpad/truss/';
const srv = http.createServer((q, r) => { r.setHeader('content-type', 'text/html; charset=utf-8'); r.end(fs.readFileSync(D + 'truss-explorer.html')); }).listen(8800);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:8800/'); await p.waitForTimeout(1200);
await p.$eval('#resOnDraw', e => { if (!e.checked) e.click(); });
await p.click('.fsbtn[data-fs="#sideSheet"]'); await p.waitForTimeout(500);
const bars = await p.evaluate(() => Math.max(...['dock', 'fsBar'].map(id => document.getElementById(id).getBoundingClientRect().bottom)));
const tc = await p.evaluate(() => document.querySelector('#resOv .tc').getBoundingClientRect().top);
console.log('2D: bars end at', bars.toFixed(0), '| capacity starts at', tc.toFixed(0));
await p.screenshot({ path: D + 'v55_fs2d.png' });
await p.click('#dockEsc'); await p.waitForTimeout(300);
await p.click('#anaSwitch [data-ana="3d"]'); await p.waitForTimeout(600);
await p.click('.fsbtn[data-fs="#sideSheet"]'); await p.waitForTimeout(500);
await p.screenshot({ path: D + 'v55_fs3d.png' });
console.log('errors:', errs.length ? errs : 'none');
srv.close(); await b.close();
